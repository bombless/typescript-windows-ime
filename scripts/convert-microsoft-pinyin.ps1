$bytes = [System.IO.File]::ReadAllBytes($InputDat)
if ($bytes.Length -lt 0x2400) { throw "File too short for Microsoft Pinyin UDL: $($bytes.Length) bytes" }
$count = [BitConverter]::ToUInt32($bytes, 0x0C)
$recordSize = 60
$start = 0x2400
$available = [Math]::Floor(($bytes.Length - $start) / $recordSize)
if ($count -gt $available) { throw "Header declares $count records but file can hold only $available; refusing partial conversion." }
$entries = [System.Collections.Generic.List[object]]::new()
$invalid = 0
$tooLong = 0
for ($i = 0; $i -lt $count; $i++) {
  $offset = $start + ($i * $recordSize)
  $wordLength = [int]$bytes[$offset + 10]
  if ($wordLength -lt 1 -or $wordLength -gt 12) { $tooLong++; continue }
  $wordByteCount = $wordLength * 2
  $word = [System.Text.Encoding]::Unicode.GetString($bytes, $offset + 12, $wordByteCount)
  if ([string]::IsNullOrWhiteSpace($word) -or $word -match '[\t\r\n]') { $invalid++; continue }
  $pinyin = [System.Collections.Generic.List[string]]::new()
  $valid = $true
  for ($j = 0; $j -lt $wordLength; $j++) {
    $indexOffset = $offset + 12 + $wordByteCount + ($j * 2)
    if ($indexOffset + 1 -ge $offset + $recordSize) { $valid = $false; break }
    $pyIndex = [BitConverter]::ToUInt16($bytes, $indexOffset)
    if ($pyIndex -ge $PinyinList.Count) { $valid = $false; break }
    $pinyin.Add($PinyinList[$pyIndex])
  }
  if (-not $valid -or $pinyin.Count -ne $wordLength) { $invalid++; continue }
  if ($word -notmatch '^\p{IsCJKUnifiedIdeographs}+$') { $invalid++; continue }
  $fullCode = $pinyin -join ''
  $initials = ($pinyin | ForEach-Object { $_.Substring(0, 1) }) -join ''
  $entries.Add([PSCustomObject]@{ Word = $word; Code = $fullCode; Initials = $initials; Weight = 1 })
}
$deduped = $entries | Sort-Object Code, Word -Unique
$temp = "$OutputYaml.tmp"
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Microsoft Pinyin user-learning dictionary converted from .dat')
$lines.Add('# Generated by scripts/convert-microsoft-pinyin.ps1; do not edit manually.')
$lines.Add('---')
$lines.Add('name: microsoft_pinyin')
$lines.Add('version: "1.0"')
$lines.Add('sort: by_weight')
$lines.Add('...')
$exportRows = [System.Collections.Generic.List[object]]::new()
foreach ($entry in $deduped) {
  $exportRows.Add([PSCustomObject]@{ Word = $entry.Word; Code = $entry.Code; Weight = $entry.Weight })
  if ($entry.Initials -and $entry.Initials -ne $entry.Code) {
    $exportRows.Add([PSCustomObject]@{ Word = $entry.Word; Code = $entry.Initials; Weight = $entry.Weight })
  }
}
$exportRows = $exportRows | Sort-Object Code, Word -Unique
foreach ($entry in $exportRows) { $lines.Add("$($entry.Word)`t$($entry.Code)`t$($entry.Weight)") }
[System.IO.File]::WriteAllLines($temp, $lines, [System.Text.UTF8Encoding]::new($false))
Move-Item -LiteralPath $temp -Destination $OutputYaml -Force
Write-Host "Input records: $count"
Write-Host "Exported unique entries: $($deduped.Count)"
Write-Host "Parsed before de-duplication: $($entries.Count)"
Write-Host "Skipped invalid records: $invalid"
Write-Host "Skipped unsupported word lengths: $tooLong"
Write-Host "Output: $OutputYaml"
